// ─── Plan check (runs before touching the database) ────────────────────────
// Every batch's numbers must add up, so remaining stock always matches its
// movement history.
function validatePlans() {
  const problems = [];
  for (const med of MEDICINES) {
    for (const b of med.batches) {
      const label = `${med.name} (${med.branch}) batch received ${b.ago} days ago`;
      const disposed = b.disposed || 0;
      const sold = b.qty - b.left - disposed + (b.ret || 0) + (b.up || 0) - (b.down || 0);
      const spike = b.spike ? b.spike.qty : 0;
      const start = -b.ago + 1;
      const end = Math.min(b.until ?? LAST_SALE_DAY, b.exp - 1, LAST_SALE_DAY);
      if (b.left < 0 || b.left > b.qty) problems.push(`${label}: remaining must be between 0 and the quantity received`);
      if (b.ago > HISTORY_DAYS) problems.push(`${label}: older than the ${HISTORY_DAYS}-day history`);
      if (sold < spike) problems.push(`${label}: sells fewer units (${sold}) than its spike (${spike})`);
      if (sold - spike > 0 && end < start) problems.push(`${label}: has units to sell but no selling days`);
      if (b.spike && (b.spike.day < start || b.spike.day > end)) problems.push(`${label}: spike falls outside its selling window`);
      if (disposed && b.exp >= 0) problems.push(`${label}: only expired batches can be disposed`);
      if (b.left === 0 && b.exp >= 0 && !b.recalled && sold === 0) problems.push(`${label}: empty batch with no sales`);
    }
  }
  if (problems.length) throw new Error(`Demo data plan is inconsistent:\n  - ${problems.join('\n  - ')}`);
}

// ─── Helpers ───────────────────────────────────────────────────────────────
function code(name) {
  return name.replace(/[^A-Za-z]/g, '').slice(0, 4).toUpperCase();
}

// Split `units` into individual customer purchases of 1–4 units.
function splitIntoSales(units) {
  const sales = [];
  while (units > 0) {
    const q = Math.min(units, randInt(1, 4));
    sales.push(q);
    units -= q;
  }
  return sales;
}

// Spread `total` units over days [start, end], weighted (optionally rising).
function spreadUnits(total, start, end, rising) {
  const days = [];
  for (let d = start; d <= end; d++) days.push(d);
  if (!days.length || total <= 0) return [];
  const weights = days.map((_, i) => (0.5 + rand()) * (rising ? 0.6 + (1.4 * i) / Math.max(1, days.length - 1) : 1));
  const sum = weights.reduce((a, b) => a + b, 0);
  const units = weights.map((w) => Math.floor((total * w) / sum));
  let remainder = total - units.reduce((a, b) => a + b, 0);
  for (let i = units.length - 1; remainder > 0; i = (i - 1 + units.length) % units.length) { units[i]++; remainder--; }
  return days.map((d, i) => [d, units[i]]).filter(([, u]) => u > 0);
}

async function demoExists() {
  const [[row]] = await pool.query("SELECT COUNT(*) AS n FROM batches WHERE batch_number LIKE 'DEMO-%'");
  return row.n > 0;
}

// ─── Reset ─────────────────────────────────────────────────────────────────
async function resetDemoData() {
  const [batches] = await pool.query("SELECT id, medicine_id FROM batches WHERE batch_number LIKE 'DEMO-%'");
  const batchIds = batches.map((b) => b.id);
  const candidateMedicineIds = [...new Set(batches.map((b) => b.medicine_id))];
  let medicineIds = [];
  if (candidateMedicineIds.length) {
    // Only medicines whose every batch is a demo batch.
    const [rows] = await pool.query(
      `SELECT m.id FROM medicines m
       WHERE m.id IN (?) AND NOT EXISTS (
         SELECT 1 FROM batches b WHERE b.medicine_id = m.id AND b.batch_number NOT LIKE 'DEMO-%'
       )`,
      [candidateMedicineIds]
    );
    medicineIds = rows.map((r) => r.id);
  }

  if (batchIds.length) {
    await pool.query("DELETE FROM notifications WHERE type IN ('near_expiry', 'expired', 'ai_risk_flag') AND reference_id IN (?)", [batchIds]);
  }
  if (medicineIds.length) {
    await pool.query("DELETE FROM notifications WHERE type IN ('low_stock', 'ai_reorder_suggestion') AND reference_id IN (?)", [medicineIds]);
  }
  // Batches cascade to their stock movements.
  if (batchIds.length) await pool.query('DELETE FROM batches WHERE id IN (?)', [batchIds]);
  if (medicineIds.length) await pool.query('DELETE FROM medicines WHERE id IN (?)', [medicineIds]);
  const [sup] = await pool.query('DELETE FROM suppliers WHERE email LIKE ?', [`%${DEMO_EMAIL_DOMAIN}`]);
  const [audit] = await pool.query('DELETE FROM audit_logs WHERE ip_address = ?', [DEMO_IP]);

  return `Removed demo data: ${medicineIds.length} medicines, ${batchIds.length} batches (with their movements), ${sup.affectedRows} suppliers, ${audit.affectedRows} audit entries.`;
}

